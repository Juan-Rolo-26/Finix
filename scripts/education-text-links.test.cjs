const assert = require('node:assert/strict');
const fs = require('node:fs');
const { createRequire } = require('node:module');
const root='/home/juampi26/Finix';
const ts=require(root+'/node_modules/typescript');
const React=require(root+'/node_modules/react');
const { renderToStaticMarkup }=require(root+'/node_modules/react-dom/server');
const sourcePath=root+'/apps/web/src/components/education/EducationText.tsx';
const moduleObject={exports:{}};
const code=ts.transpileModule(fs.readFileSync(sourcePath,'utf8'),{compilerOptions:{jsx:ts.JsxEmit.ReactJSX,module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
new Function('require','module','exports',code)(createRequire(sourcePath),moduleObject,moduleObject.exports);
const credit='*Autor: Samuel Boote. Licencia: [Dominio público](https://creativecommons.org/publicdomain/mark/1.0/). Fuente: [Wikimedia Commons](https://commons.wikimedia.org/wiki/File:Bolsa_de_Comercio_(Buenos_Aires).jpg).*';
const output=renderToStaticMarkup(React.createElement('div',null,moduleObject.exports.renderEducationText(credit)));
assert(output.includes('<em>'));
assert(output.includes('href="https://commons.wikimedia.org/wiki/File:Bolsa_de_Comercio_(Buenos_Aires).jpg"'));
assert(output.includes('href="https://creativecommons.org/publicdomain/mark/1.0/"'));
assert(!output.includes('[Wikimedia'));
const unsafe=renderToStaticMarkup(React.createElement('div',null,moduleObject.exports.renderEducationText('[x](javascript:alert(1)) <script>bad()</script>')));
assert(!unsafe.includes('href="javascript:'));
assert(!unsafe.includes('<script>'));
console.log('PASS: readable italic credits, complete parenthesized URLs, safe links and escaped HTML');
