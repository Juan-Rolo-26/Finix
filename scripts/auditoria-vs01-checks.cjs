const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const { writeFileSync } = require('node:fs');
const { setup, capture, OUT, BASE } = require('./auditoria-ux-vscode.browser.cjs');
(async () => {
    const browser = await chromium.launch({ headless: true, args: ['--disable-gpu'] });
    const results = [];
    try {
        const { page, errors, writes } = await setup(browser);
        await page.goto(`${BASE}/login?mode=register&redirect=%2Fmessages`, { waitUntil: 'domcontentloaded' });
        await page.getByLabel('Nombre de usuario', { exact: true }).fill('ab');
        await page.getByLabel('Correo electrónico', { exact: true }).fill('inválido');
        await page.getByLabel('Contraseña', { exact: true }).fill('corta');
        await page.locator('button[type=submit]').click();
        await page.locator('#auth-username-error').waitFor();
        assert.equal(writes.filter(path => path.startsWith('/auth/register')).length, 0, 'Invalid registration cannot issue an API request');
        assert.equal(await page.locator('#auth-password').getAttribute('aria-invalid'), 'true');
        assert.ok((await page.locator('#auth-password').getAttribute('aria-describedby')).includes('auth-password-error'));
        await capture(page, 'vs01-registro-errores-390-light');
        results.push('Reglas visibles, errores por campo asociados y foco en el primer error; no se envía registro inválido.');
        await page.goto(`${BASE}/login?redirect=%2Fmessages`);
        await page.getByLabel('Correo electrónico', { exact: true }).fill('audit@example.invalid');
        await page.getByLabel('Contraseña', { exact: true }).fill('Audit-UI-only');
        await page.getByRole('button', { name: 'Mostrar contraseña', exact: true }).click();
        assert.equal(await page.locator('#auth-password').getAttribute('type'), 'text');
        await page.keyboard.press('Tab');
        assert.notEqual(await page.evaluate(() => document.activeElement.tagName), 'BODY');
        await page.locator('button[type=submit]').click();
        await page.getByText('El correo o la contraseña no son correctos.', { exact: false }).waitFor();
        results.push('Credenciales incorrectas: mensaje específico en español; mostrar/ocultar y teclado comprobados.');
        await page.route('**/api/auth/login/request-code', route => route.fulfill({ status: 503, json: { message: 'API key is invalid' } }));
        await page.locator('button[type=submit]').click();
        await page.getByText('El servicio de acceso no está disponible.', { exact: false }).waitFor();
        await capture(page, 'vs01-login-servicio-error-390-light');
        results.push('API key is invalid normalizado; recuperación mediante reintento y enlace Ayuda.');
        await page.route('**/api/auth/login/request-code', route => route.fulfill({ json: { success: true } }));
        await page.locator('button[type=submit]').click();
        await page.getByLabel('Código de verificación', { exact: true }).waitFor();
        assert.equal(new URL(page.url()).pathname, '/login', 'OTP is still required');
        await page.getByLabel('Código de verificación', { exact: true }).fill('123456');
        await page.route('**/api/auth/login/verify-code', route => route.fulfill({ json: { token: 'isolated-ui-fixture', user: { id: 'preview', username: 'inversor', onboardingCompleted: true } } }));
        await page.locator('button[type=submit]').click();
        await page.waitForURL('**/messages');
        results.push('Contrato UI de acceso en dos pasos preserva /messages. Fixture aislado: no prueba acceso real.');
        await page.close();
        const guest = await setup(browser);
        await guest.page.goto(`${BASE}/login?redirect=%2Fmessages`);
        await guest.page.getByRole('button', { name: 'Google', exact: true }).click();
        await guest.page.getByText('El acceso con Google todavía no está configurado.', { exact: false }).waitFor();
        await guest.page.evaluate(() => sessionStorage.setItem('authRedirect', '/messages'));
        await guest.page.goto(`${BASE}/auth/callback?error=invalid_client`);
        await guest.page.waitForURL('**/login?reason=google-auth-error&redirect=%2Fmessages');
        results.push('Google no configurado y error de callback recuperables, con /messages conservado. Acceso Google real pendiente.');
        await guest.page.goto(`${BASE}/market/seguimiento`);
        await guest.page.getByRole('button', { name: 'Nueva lista', exact: true }).first().click();
        await guest.page.getByRole('dialog', { name: 'Ingresá para continuar' }).waitFor();
        assert.equal(await guest.page.getByPlaceholder('Ej. CEDEARs', { exact: false }).count(), 0);
        assert.ok((await guest.page.getByRole('link', { name: 'Iniciar sesión', exact: true }).last().getAttribute('href')).includes('redirect=%2Fmarket%2Fseguimiento'));
        await capture(guest.page, 'vs01-lista-cuenta-requerida-390-light');
        await guest.page.keyboard.press('Escape');
        await guest.page.getByRole('dialog').waitFor({ state: 'hidden' });
        results.push('Nueva lista visitante pide cuenta antes de escribir y conserva destino; cierre Escape.');
        await guest.page.goto(`${BASE}/explore?create=true`);
        await guest.page.getByRole('dialog', { name: 'Ingresá para continuar' }).waitFor();
        assert.equal(await guest.page.locator('textarea').count(), 0, 'Guest cannot invest effort in a private composer');
        await capture(guest.page, 'vs01-publicacion-cuenta-requerida-390-light');
        results.push('Crear publicación visitante solicita cuenta antes del compositor; no se puede perder un borrador inicial.');
        assert.deepEqual(errors, []);
        assert.deepEqual(guest.errors, []);
        writeFileSync(`${OUT}/vs01-criterios.json`, JSON.stringify({ results, realLogin: 'bloqueado: requiere credenciales y proveedor desplegado', errors }, null, 2));
        console.log(results.join('\n'));
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
